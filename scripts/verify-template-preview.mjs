  const app = express();
  app.use("/template-preview", (request, response) => {
    if (!["GET", "HEAD"].includes(request.method)) return response.sendStatus(405);
    let file = path.resolve(directory, `.${decodeURIComponent(request.path)}`);
    if (file !== directory && !file.startsWith(directory + path.sep)) return response.sendStatus(403);
    if (fs.existsSync(file) && fs.statSync(file).isDirectory()) file = path.join(file, "index.html");
    if (!fs.existsSync(file)) file = file.replace(/\/$/, "") + ".html";
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) return response.sendStatus(404);
    response.set("Cache-Control", "no-store").sendFile(file);
  });
  fixtureServer = await new Promise(resolve => { const server = app.listen(0, "127.0.0.1", () => resolve(server)); });
  fixtureServer.unref();
  previewURL = `http://127.0.0.1:${fixtureServer.address().port}/template-preview/`;
