async function verifyHomeScroll(page, width) {
  const home = new URL("?fx=off", base).href;
  for (const reload of [false, true]) {
    await page.goto(new URL("stations-prep.html", base).href);
    await page.goto(home);
    if (reload) await page.reload();
    await page.waitForTimeout(1000);
    assert.equal(await page.evaluate(() => scrollY), 0, `fresh/reload top ${width}`);
    await page.evaluate(() => history.replaceState({ ...history.state, scrollTest: "retained" }, ""));
    const link = page.locator('footer a[href*="stations-prep"]').last();
    await link.scrollIntoViewIfNeeded();
    await page.waitForTimeout(500);
    const before = await link.evaluate(element => element.getBoundingClientRect().top);
    await link.click();
    await page.waitForURL("**/stations-prep.html*");
    await page.goBack({ waitUntil: "load" });
    await page.waitForTimeout(2700);
    const after = await page.locator('footer a[href*="stations-prep"]').last().evaluate(element => element.getBoundingClientRect().top);
    assert(Math.abs(after - before) < 10, `Back returns to the clicked link ${width}/${reload}: ${before} → ${after}`);
    assert.equal(await page.evaluate(() => history.state.scrollTest), "retained");
    assert.equal(await page.evaluate(() => history.scrollRestoration), "auto");
    await page.goForward({ waitUntil: "load" });
    await page.goBack({ waitUntil: "load" });
    await page.waitForTimeout(2700);
    const again = await page.locator('footer a[href*="stations-prep"]').last().evaluate(element => element.getBoundingClientRect().top);
    assert(Math.abs(again - before) < 10, `repeated Forward/Back ${width}/${reload}`);
  }
  await page.goto(new URL("stations-prep.html", base).href);
  await page.goto(new URL("?fx=off#ask", base).href);
  await page.waitForTimeout(1000);
  assert(await page.evaluate(() => scrollY > 1000), `fresh hash honoured ${width}`);
  await page.reload();
  await page.waitForTimeout(1000);
  assert.equal(new URL(page.url()).hash, "");
  assert.equal(await page.evaluate(() => scrollY), 0);
}
